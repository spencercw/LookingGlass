void updateUniformBuffer(Vulkan_Cursor * this, int width, int height)
{
  struct CursorPos  pos  = atomic_load(&this->pos );
  struct CursorPos  hs   = atomic_load(&this->hs  );

  pos.x -= hs.x;
  pos.y -= hs.y;

  struct UniformBuffer uniformBuffer = {
    .renderTargetSize = { width, height },
    .cursorPos = {
      (int32_t) lrintf((pos.x + 1.0f) * (float) width / 2.0f),
      (int32_t) lrintf((pos.y + 1.0f) * (float) height / 2.0f)
    }
  };

  memcpy(this->uniformBufferMap, &uniformBuffer, sizeof(uniformBuffer));
}

bool vulkan_cursorRender(Vulkan_Cursor * this, VkImageView renderTarget,
    LG_RendererRotate rotate, int width, int height)
{
  if (!this->visible)
    return true;

  if (rotate != LG_ROTATE_0)
    DEBUG_ERROR("Cursor rotation %d not implemented", rotate);

  if (this->update)
  {
    LG_LOCK(this->lock);
    this->update = false;

    if (!createImage(this))
    {
      LG_UNLOCK(this->lock);
      return false;
    }

    updateImage(this);

    LG_UNLOCK(this->lock);
  }

  updateUniformBuffer(this, width, height);

  updateDescriptorSet(this, renderTarget);

  vkCmdBindPipeline(this->commandBuffer, VK_PIPELINE_BIND_POINT_COMPUTE,
      this->pipeline);

  vkCmdBindDescriptorSets(this->commandBuffer,
      VK_PIPELINE_BIND_POINT_COMPUTE, this->pipelineLayout, 0, 1,
      &this->descriptorSet, 0, NULL);

  uint32_t groupCount = this->imageSize / 16;
  vkCmdDispatch(this->commandBuffer, groupCount, groupCount, 1);

  return true;
}
