  if (!*cursor)
  {
    DEBUG_ERROR("Failed to malloc Vulkan_Cursor");
    goto err;
  }

  LG_LOCK_INIT((*cursor)->lock);
  (*cursor)->memoryProperties = memoryProperties;
  (*cursor)->device = device;
  (*cursor)->commandBuffer = commandBuffer;
  (*cursor)->descriptorPool = descriptorPool;

  (*cursor)->computeShader = vulkan_loadShader(device,
      b_shader_cursor_rgb_comp_spv, b_shader_cursor_rgb_comp_spv_size - 1);
  if (!(*cursor)->computeShader)
    goto err_cursor;

  if (!createDescriptorSetLayout(*cursor))
    goto err_shader;

  (*cursor)->descriptorSet = vulkan_allocateDescriptorSet(device,
      (*cursor)->descriptorSetLayout, descriptorPool);
  if (!(*cursor)->descriptorSet)
    goto err_descriptor_set_layout;

